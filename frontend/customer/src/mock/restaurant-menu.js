let _menuId = 1000
export const restaurantMenu = {
  categories: RAW.map((cat, ci) => {
    const pool = IMG[cat.imgs] || IMG.main
    return {
      id: ci + 1,
      name: cat.name,
      display_order: ci,
      menus: cat.items.map(([name, price, description, imgIdx, isAvail], mi) => ({
        id: (_menuId += 1),
        name,
        price,
        description,
        image_url: pool[imgIdx % pool.length],
        display_order: mi,
        is_available: isAvail === undefined ? true : isAvail,
      })),
    }
  }),
}

